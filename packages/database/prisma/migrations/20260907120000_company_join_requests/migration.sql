-- A colleague of an existing member can apply to join their company.
--
-- Until now a second person at a company that was already registered had one
-- route in: their administrator typed their address into the team page. If
-- nobody did, the CR check refused them ("A company is already registered with
-- that commercial registration number") and the journey ended there.
--
-- This adds the two things that route needed and did not have:
--
--   Company.emailDomains  the domains a company is recognised at, so that
--                         "does this person actually work there?" has an answer
--                         before a human is asked to look.
--   CompanyJoinRequest    the application itself, which is NOT a membership. A
--                         membership row is authority (getB2BContext reads it to
--                         decide whose prices a user sees); this row is a
--                         request, and grants nothing until an administrator of
--                         that company promotes it.
--
-- GENERATED BY `prisma migrate diff`, not hand-written, then commented. The
-- hand-written alternative is what produced two migrations for one schema
-- change on this repo's last merge — one of them incomplete, and the pair
-- unrunnable in sequence. The backfill at the end is the only statement here
-- that diff did not write.
--
-- ADDITIVE. No column is dropped and no constraint narrowed.

