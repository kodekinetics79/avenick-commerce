-- ─── Backfill: recognise each company at its founding admin's own domain ───
--
-- Without this every existing company starts with an empty list and the feature
-- is dark for all of them until somebody edits a row by hand.
--
-- Two conditions, both load-bearing:
--
--   1. COMPANY_ADMIN members only. A buyer invited from a personal address must
--      not be able to teach the company a domain.
--   2. NOT a public mailbox provider. A company whose administrator registered
--      with a gmail.com address must never come to claim gmail.com — that would
--      let any Gmail user on earth pass its "do you work here?" gate, which is
--      precisely the hole this feature exists to close. Such companies keep an
--      empty list and stay invite-only, which is the right answer and not a gap.
--
-- The provider list is duplicated from isPublicMailboxDomain() in
-- packages/utils. That is deliberate: SQL running once at migration time cannot
-- import TypeScript, and leaving the backfill out is worse than two copies of a
-- list that changes about once a decade.
UPDATE "Company" c
SET "emailDomains" = ARRAY[sub.domain]
FROM (
  SELECT DISTINCT ON (m."companyId")
         m."companyId",
         lower(split_part(u."email", '@', 2)) AS domain
  FROM "CompanyMember" m
  JOIN "User" u ON u."id" = m."userId"
  WHERE m."role" = 'COMPANY_ADMIN'
    AND m."isActive" = true
    AND position('@' in u."email") > 0
  ORDER BY m."companyId", m."joinedAt" ASC
) sub
WHERE c."id" = sub."companyId"
  AND sub.domain <> ''
  AND sub.domain NOT IN (
    'gmail.com', 'googlemail.com', 'yahoo.com', 'yahoo.co.uk', 'ymail.com',
    'hotmail.com', 'hotmail.co.uk', 'outlook.com', 'live.com', 'msn.com',
    'icloud.com', 'me.com', 'mac.com', 'aol.com', 'proton.me', 'protonmail.com',
    'gmx.com', 'gmx.net', 'mail.com', 'zoho.com', 'yandex.com', 'yandex.ru',
    'qq.com', '163.com', '126.com', 'naver.com', 'hushmail.com',
    'mailinator.com', 'yopmail.com', 'guerrillamail.com', '10minutemail.com',
    'tempmail.com', 'temp-mail.org', 'trashmail.com', 'sharklasers.com',
    'dispostable.com', 'getnada.com', 'maildrop.cc', 'fakeinbox.com'
  );
