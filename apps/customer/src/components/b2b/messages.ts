/**
 * The B2B buyer suite's message catalogue — every user-visible string in
 * apps/customer/src/app/b2b/**, in both languages.
 *
 * WHY IT LIVES HERE RATHER THAN IN messages/{en,ar}.json
 * ------------------------------------------------------
 * It should live there, under a `b2b` namespace, and the keys below are already
 * shaped for exactly that fold: they are flat dotted paths, which is precisely
 * what next-intl produces when you nest an object. `t("dash.open.title")` here
 * becomes `useTranslations("b2b")("dash.open.title")` there, with no other edit
 * to any page. The catalogue is a separate module only because the shared
 * message tree is written by several tracks at once and a concurrent write to
 * one JSON file silently drops another track's namespace.
 *
 * See the cross-track request in the handover note: fold `B2B_MESSAGES.en` into
 * messages/en.json under `"b2b"`, `B2B_MESSAGES.ar` into messages/ar.json,
 * then replace `getB2BT()` with `getTranslations("b2b")`.
 *
 * THE ARABIC IS NOT A TRANSLATION OF THE ENGLISH.
 * Procurement Arabic has its own settled vocabulary — أمر شراء, طلب عرض سعر,
 * الحد الائتماني, أعمار الديون — and a literal rendering of the English reads
 * as software nobody in the Gulf wrote. Where a sentence carries provenance
 * (what a figure is drawn from, and why two currencies are not added together)
 * the Arabic states the same fact in the same register rather than transliterating
 * the English clause order.
 *
 * NO STRING HERE MAY CLAIM ANYTHING THE DATABASE DOES NOT HOLD. Several of these
 * sentences exist specifically to state a limit — that a window is 100 rows, that
 * no exchange rate exists, that no alert is sent when a quote lands. Those are
 * the sentences that make the figures trustworthy; do not "tighten" them away.
 */

