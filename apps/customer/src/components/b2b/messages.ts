export const B2B_MESSAGES = { en, ar } as const;

/** The translator signature. Matches next-intl's `t(key, values)` shape. */
export type B2BT = (key: B2BKey, values?: Record<string, string | number>) => string;

/**
 * Build a translator for a locale.
 *
 * Interpolation is `{name}`, the ICU-lite subset next-intl uses for simple
 * substitution, so folding this catalogue into the shared message tree needs no
 * edit to any call site. Plurals are two explicit keys (`.one` / `.other`)
 * chosen by the caller rather than an ICU plural, because Arabic has six plural
 * categories and a two-form ICU rule written by an English speaker is wrong in
 * Arabic more often than it is right — the pages here only ever distinguish "one"
 * from "more than one", and they say so.
 */
export function b2bT(locale: string | undefined): B2BT {
  const dict: Record<B2BKey, string> = locale === "ar" ? ar : en;
  return (key, values) => {
    const template = dict[key] ?? en[key] ?? key;
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : whole,
    );
  };
}
